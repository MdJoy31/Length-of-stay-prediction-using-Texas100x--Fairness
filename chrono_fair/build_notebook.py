"""Generate CHRONO_Fair_End_to_End.ipynb, the reproducible analysis notebook.

The notebook imports the chrono_fair package, builds the dataset, runs every
experiment, and displays each figure inline. Run this builder, then execute
the notebook with nbconvert (see chrono_fair/README.md).
"""
from __future__ import annotations
import os
import nbformat as nbf


def md(text):
    return nbf.v4.new_markdown_cell(text)


def code(text):
    return nbf.v4.new_code_cell(text)


def build():
    nb = nbf.v4.new_notebook()
    cells = []

    cells.append(md(
        "# CHRONO-Fair: End-to-End Reproducible Analysis\n\n"
        "Anytime-valid counterfactual flip monitoring for clinical machine "
        "learning.\n\n"
        "This notebook reproduces every experiment and figure in the paper. "
        "It uses two data sources.\n\n"
        "1. **Synthetic stream** (`data/texas100x_synthetic_stream.csv`). "
        "Generated by the calibrated synthesiser. Its demographic mix and "
        "class balance match the published Texas-100X statistics. It is not "
        "the real discharge data.\n"
        "2. **Real audit artefacts** (`data/real_texas100x_audit_artifacts.json`). "
        "Real 1000-iteration bootstrap confidence intervals and 20-resample "
        "fluctuation arrays computed by the parent repository on the full "
        "real Texas-100X dataset (925,128 records).\n\n"
        "Every numerical claim in the paper is produced by a cell below. "
        "No result is hard-coded."))

    cells.append(md("## 0. Environment setup"))
    cells.append(code(
        "import os, sys, json\n"
        "import numpy as np, pandas as pd\n"
        "import matplotlib.pyplot as plt\n"
        "from IPython.display import Image, display\n\n"
        "# Resolve repository root so the notebook runs from any directory\n"
        "ROOT = os.path.abspath(os.path.join(os.getcwd(), '..'))\n"
        "if os.path.basename(os.getcwd()) != 'chrono_fair':\n"
        "    ROOT = os.getcwd()\n"
        "sys.path.insert(0, ROOT)\n"
        "FIG = os.path.join(ROOT, 'chrono_fair_figures')\n"
        "print('repo root :', ROOT)\n"
        "print('figures   :', FIG)\n"
        "import chrono_fair\n"
        "print('chrono_fair version:', chrono_fair.__version__)"))

    cells.append(md(
        "## 1. Build the dataset\n\n"
        "Writes the synthetic stream and copies the real audit artefacts "
        "into `chrono_fair/data/`. See `data/DATA_CARD.md` for provenance."))
    cells.append(code(
        "from chrono_fair.data.build_dataset import main as build_data\n"
        "build_data()\n"
        "df = pd.read_csv(os.path.join(ROOT, 'chrono_fair', 'data',\n"
        "                              'texas100x_synthetic_stream.csv'))\n"
        "print('\\nsynthetic stream shape:', df.shape)\n"
        "display(df.head())\n"
        "print('\\nrace mix:'); display(df['race'].value_counts())\n"
        "print('extended-stay balance:', round(df['y_ext'].mean(), 3))"))

    cells.append(md(
        "## 2. Component check: the four estimators\n\n"
        "A quick functional check that each of the four estimators runs and "
        "returns the expected object type."))
    cells.append(code(
        "from chrono_fair.flip_hazard import kaplan_meier_curve, logrank_two_groups\n"
        "from chrono_fair.e_process import EProcessMonitor\n"
        "from chrono_fair.decomposition import ensemble_decompose\n"
        "from chrono_fair.rcap import rank_shift, wasserstein_rcap_ci\n\n"
        "rng = np.random.default_rng(0)\n"
        "z = (rng.random(800) < 0.12).astype(int)\n"
        "km = kaplan_meier_curve(np.arange(800.0), z)\n"
        "print('Flip Hazard  : KM final survival =', round(km['S'].iloc[-1], 4))\n\n"
        "mon = EProcessMonitor(rho0=0.05, alpha=0.05)\n"
        "for v in (rng.random(3000) < 0.15).astype(int):\n"
        "    mon.update(int(v))\n"
        "print('E-process    : alarm at patient', mon.alarm_at)\n\n"
        "pa = rng.random((7, 500)); pc = rng.random((7, 500))\n"
        "dec = ensemble_decompose(pa, pc)\n"
        "print('Decomposition: mean flip mass =', round(dec['p_flip_bar'].mean(), 4))\n\n"
        "d = rng.normal(0, 0.1, 400)\n"
        "m, lo, hi = wasserstein_rcap_ci(d)\n"
        "print('RCAP         : W1 =', round(m, 4), 'CI =', (round(lo,4), round(hi,4)))"))

    # experiment sections
    experiments = [
        ("3. Architecture and concept diagrams",
         "exp0_architecture_diagram",
         ["fig0_architecture.png"],
         "The framework architecture and the VFR-Audit to CHRONO-Fair "
         "conceptual mapping."),
        ("3b. VFR-Audit to CHRONO-Fair concept",
         "exp0b_concept_diagram",
         ["fig_concept_vfr_to_chrono.png"],
         "VFR-Audit is a static batch scalar. CHRONO-Fair is the streaming "
         "extension; the scalar VFR is recovered as 1 - S at the audit "
         "horizon."),
        ("4. Experiment 1: detection delay",
         "exp1_detection_delay",
         ["fig1_detection_delay.png"],
         "Patients-to-alarm after an injected drift, CHRONO-Fair against "
         "ADWIN, Davis-ADWIN, a periodic batch test, and static VFR."),
        ("5. Experiment 2: aleatoric/epistemic decomposition",
         "exp2_decomposition_accuracy",
         ["fig2_decomposition_confusion.png",
          "fig2b_synthetic_validation.png"],
         "Controlled validation of the decomposition, and the ML-driven "
         "track that yields mixed root causes."),
        ("6. Experiment 3: Flip Hazard survival",
         "exp3_flip_hazard_curves",
         ["fig3_km_curves_race.png", "fig3_km_curves_intersectional.png",
          "fig3b_rmft_vs_vfr.png"],
         "Group-stratified Kaplan-Meier flip survival, intersectional "
         "curves, and the RMFT against scalar VFR."),
        ("7. Experiment 4: RCAP for length-of-stay regression",
         "exp4_rcap_los",
         ["fig4_rcap_rank_shift.png", "fig4b_rcap_vs_mae_gap.png"],
         "Wasserstein-1 counterfactual rank shift, with bootstrap CIs, "
         "against the group-MAE comparator."),
        ("8. Experiment 5: false-alarm calibration and ablation",
         "exp5_ablation_false_alarm",
         ["fig5a_false_alarm_calibration.png", "fig5b_ablation.png"],
         "Empirical false-alarm rate against nominal alpha, confirming the "
         "anytime-valid control."),
        ("9. Experiment 6: sensitivity to drift magnitude",
         "exp6_sensitivity",
         ["fig7_sensitivity.png"],
         "Detection rate and delay as the post-drift rate varies."),
        ("10. Experiment 7: four-attribute audit",
         "exp7_all_attributes",
         ["fig8_four_attribute_audit.png"],
         "Flip Hazard survival across race, ethnicity, sex, and age group."),
        ("11. Experiment 8: real Texas-100X verdict stability",
         "exp8_real_vfr_analysis",
         ["fig9_real_vfr_forest.png"],
         "Real-data analysis. Point estimate against bootstrap CI against "
         "VFR on the 12 audited metric-attribute combinations."),
        ("12. Experiment 9: robustness stress tests",
         "exp9_robustness",
         ["fig10_robustness.png"],
         "Baseline miscalibration, small-subgroup reliability, and label "
         "delay."),
        ("13. Experiment C: multiple-testing procedures",
         "exp10_online_fdr",
         ["fig11_online_fdr.png"],
         "Step-wise BH against e-BH against Bonferroni on the "
         "intersectional cell set."),
        ("14. Experiment D: counterfactual-definition sensitivity",
         "exp11_counterfactual_sensitivity",
         ["fig12_cf_sensitivity.png"],
         "Group flip rate under the naive-swap, feature-shift, and "
         "proxy-adjusted counterfactual definitions."),
        ("15. Experiment E: full module ablation",
         "exp12_ablation_full",
         ["fig13_ablation_full.png"],
         "Effect of removing the warm-up, the GROW rule, the shrinkage, and "
         "the one-sided clip."),
        ("16. Experiment I: correlated arrivals",
         "exp13_correlated_arrivals",
         ["fig14_correlated_arrivals.png"],
         "False-alarm rate and detection delay under AR(1) autocorrelated "
         "arrival streams."),
        ("17. Experiment 14: real Texas-100 flip rate",
         "exp14_real_texas100",
         ["fig15_real_texas100.png"],
         "Real-data validation. Ensemble decision-flip rate and Flip Hazard "
         "survival on the real Texas-100 dataset (67,330 records). Uses the "
         "12,000-record real subsample shipped in data/ if the full file is "
         "absent."),
        ("18. Dashboard rendering",
         "dashboard.mockup",
         ["fig6_dashboard_mockup.png"],
         "The four-panel monitoring dashboard with the Inspector report "
         "card."),
    ]

    for title, module, figs, desc in experiments:
        cells.append(md(f"## {title}\n\n{desc}"))
        runner = ("from chrono_fair.dashboard.mockup import main as _m\n_m()"
                  if module == "dashboard.mockup"
                  else f"from chrono_fair.experiments.{module} "
                       f"import main as _m\n_m()")
        cells.append(code(
            "import warnings; warnings.filterwarnings('ignore')\n"
            + runner))
        disp = "\n".join(
            f"display(Image(filename=os.path.join(FIG, '{f}')))"
            for f in figs)
        cells.append(code(disp))

    cells.append(md(
        "## 19. Summary\n\n"
        "All 16 experiment blocks above ran from source. The figures are "
        "regenerated into `chrono_fair_figures/` and the per-experiment CSV "
        "outputs alongside them. The real-data component (Experiment 8) uses "
        "the stored real audit artefacts; every other experiment uses the "
        "calibrated synthesiser. Real EHR temporal validation on MIMIC-IV or "
        "eICU is the stated next step and is not part of this notebook, "
        "because it requires credentialed PhysioNet access."))

    nb['cells'] = cells
    nb['metadata'] = {
        'kernelspec': {'display_name': 'Python 3', 'language': 'python',
                        'name': 'python3'},
        'language_info': {'name': 'python', 'version': '3.11'},
    }
    out = os.path.join(os.path.dirname(__file__),
                        'CHRONO_Fair_End_to_End.ipynb')
    with open(out, 'w') as fh:
        nbf.write(nb, fh)
    print('Wrote', out, 'with', len(cells), 'cells')


if __name__ == '__main__':
    build()
