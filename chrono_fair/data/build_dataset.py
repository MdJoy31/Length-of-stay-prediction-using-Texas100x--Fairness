"""
Build and persist the CHRONO-Fair evaluation datasets into chrono_fair/data/.

Two artefacts are written.

  1. texas100x_synthetic_stream.csv
     A synthetic patient stream. It is NOT the real Texas-100X discharge
     data. The real Public Use Data File requires a download from the Texas
     Department of State Health Services and cannot be redistributed. This
     file is generated by the calibrated synthesiser in
     chrono_fair/data/synthesizer.py. Its demographic mix and class balance
     match the published Texas-100X statistics (925,128 records, 5 racial
     groups, 4 protected attributes, ~55/45 extended-stay balance). The
     feature schema follows the 10-feature layout of the official
     process_texas.py script.

  2. real_texas100x_audit_artifacts.json
     A copy of the real fairness-audit results computed by the parent
     repository on the full Texas-100X dataset. These are real numbers:
     1000-iteration bootstrap confidence intervals and 20-resample
     hospital-network fluctuation arrays for DI, WTPR, SPD, EOD, and
     PPV ratio across RACE, ETHNICITY, SEX, and AGE_GROUP. Experiment 8
     (exp8_real_vfr_analysis.py) reads this file.

Run: python -m chrono_fair.data.build_dataset
"""
from __future__ import annotations
import os
import json
import shutil

from chrono_fair.data.synthesizer import generate_stream, StreamConfig


def main() -> None:
    here = os.path.dirname(__file__)
    repo_root = os.path.join(here, '..', '..')
    out_dir = here  # chrono_fair/data/

    # ---- 1. synthetic stream ----
    cfg = StreamConfig(n=30_000, seed=42, drift_at=18_000,
                        drift_magnitude=0.6, aleatoric_bias=0.05)
    df = generate_stream(cfg)
    csv_path = os.path.join(out_dir, 'texas100x_synthetic_stream.csv')
    df.to_csv(csv_path, index=False)
    print(f'Wrote {csv_path}  ({len(df)} rows, {df.shape[1]} columns)')
    print(f'  drift onset at arrival index {cfg.drift_at}')
    print(f'  race mix: {df.race.value_counts().to_dict()}')

    # ---- 1b. temporal 70/15/15 train / validation / test split ----
    # The split is by arrival index, not random. In a deployment setting the
    # model is trained and the baseline rho_0 is calibrated on the earliest
    # records; the monitor then runs on later, unseen records. A temporal
    # split avoids leakage of future case mix into training.
    n = len(df)
    i_tr = int(0.70 * n)
    i_va = int(0.85 * n)
    splits = {
        'train': df.iloc[:i_tr],
        'val':   df.iloc[i_tr:i_va],
        'test':  df.iloc[i_va:],
    }
    split_dir = os.path.join(out_dir, 'splits')
    os.makedirs(split_dir, exist_ok=True)
    manifest = {'split_rule': 'temporal 70/15/15 by arrival index',
                'n_total': n, 'drift_onset_index': cfg.drift_at, 'parts': {}}
    for name, part in splits.items():
        p = os.path.join(split_dir, f'texas100x_synthetic_{name}.csv')
        part.to_csv(p, index=False)
        manifest['parts'][name] = {
            'n': len(part),
            'index_range': [int(part['patient_id'].min()),
                             int(part['patient_id'].max())],
            'extended_stay_rate': round(float(part['y_ext'].mean()), 4),
            'contains_drift': bool(part['patient_id'].max() >= cfg.drift_at),
        }
        print(f'  split {name:5s}: n={len(part):6d}  '
               f'ext-stay={part["y_ext"].mean():.3f}  -> {p}')
    with open(os.path.join(split_dir, 'split_manifest.json'), 'w') as fh:
        json.dump(manifest, fh, indent=1)
    print(f'  wrote {os.path.join(split_dir, "split_manifest.json")}')

    # ---- 2. real audit artefacts ----
    src = os.path.join(repo_root, 'results', 'paper_analysis_all.json')
    dst = os.path.join(out_dir, 'real_texas100x_audit_artifacts.json')
    if os.path.exists(src):
        with open(src) as fh:
            full = json.load(fh)
        # keep only the real-data audit fields used by Experiment 8
        subset = {
            'source': 'Parent repository real-data audit on Texas-100X '
                      '(925,128 records, 185,026-record test set).',
            'dataset_info': full.get('dataset_info', {}),
            'bootstrap_ci': full.get('bootstrap_ci', {}),
            'fluctuation': full.get('fluctuation', {}),
        }
        with open(dst, 'w') as fh:
            json.dump(subset, fh, indent=1)
        print(f'Wrote {dst}  (real bootstrap CIs and fluctuation arrays)')
    else:
        print(f'WARNING: {src} not found; real-audit artefact not copied.')

    # ---- 3. data card ----
    card = os.path.join(out_dir, 'DATA_CARD.md')
    with open(card, 'w') as fh:
        fh.write(_DATA_CARD)
    print(f'Wrote {card}')


_DATA_CARD = """# CHRONO-Fair data folder

This folder holds the evaluation data for the CHRONO-Fair experiments.

## texas100x_synthetic_stream.csv

Synthetic. Generated by `chrono_fair/data/synthesizer.py`. This is **not**
the real Texas-100X discharge data. The real Public Use Data File requires
a download from the Texas Department of State Health Services
(https://www.dshs.texas.gov/) and may not be redistributed.

Calibration targets (matched to the published Texas-100X statistics):
- 5 racial groups: White 48%, Hispanic 30%, Black 13%, Asian/PI 5%, Other 4%
- Sex: Female 55%, Male 45%
- Ethnicity: Non-Hispanic 65%, Hispanic 35%
- Age groups: Pediatric 5%, Young Adult 20%, Middle-aged 40%, Elderly 35%
- Binary extended-stay target balance approximately 55/45

Columns: arrival, patient_id, race, sex, ethnicity, age_group, age_years,
y_los (continuous length of stay), y_ext (extended stay > 3 days),
x0..x11 (clinical risk features). A structural disparity of +0.4 on
features x0..x2 is injected for Black and Hispanic groups, and a temporal
drift begins at arrival index 18,000.

## real_texas100x_audit_artifacts.json

Real. A copy of the fairness-audit results computed by the parent
repository on the full real Texas-100X dataset. Contains 1000-iteration
bootstrap confidence intervals and 20-resample hospital-network
fluctuation arrays for DI, WTPR, SPD, EOD, and PPV ratio across RACE,
ETHNICITY, SEX, and AGE_GROUP. Experiment 8 reads this file. No raw
patient records are included; only aggregate audit statistics.

## texas100_real_subsample.npz

Real. A 12,000-record subsample of the real Texas-100 dataset of Shokri
et al. (the membership-inference Texas-100, 67,330 records, 6,169
normalised categorical features, 100-class surgical-procedure label).
Stored compressed (float32) at under 1 MB because the feature matrix is
sparse. Experiment 14 (exp14_real_texas100.py) loads the full file if it
is present, and falls back to this subsample otherwise.

Honest scope note. Texas-100 is not Texas-100X. It is smaller, the task is
100-class procedure prediction rather than length of stay, and the
released file does not include the official feature-description file. The
6,169 columns therefore cannot be mapped to named protected attributes.
Experiment 14 validates the flip and Flip Hazard machinery on these real
records; it does not run group-stratified fairness on them.

## Splits

`splits/` holds a temporal 70/15/15 train/validation/test partition of the
synthetic stream, with `split_manifest.json` recording the index ranges
and class balance of each part.

## How to obtain the real raw data

Texas-100 (Shokri et al.): the features and labels pickle files are
distributed publicly; the 12,000-record subsample here is derived from
them.

Texas-100X (named-column, length-of-stay): the GitHub repository
https://github.com/bargavj/Texas-100X contains only process_texas.py.
The raw Public Use Data File must be downloaded from the Texas Department
of State Health Services (https://www.dshs.texas.gov/), after which
process_texas.py produces texas_100x.csv. That file is required for
group-stratified fairness analysis on the real length-of-stay task.
"""


if __name__ == '__main__':
    main()
